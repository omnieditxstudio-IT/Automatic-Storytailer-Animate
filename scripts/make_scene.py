#!/usr/bin/env python3
"""Write the project's scene.py, the one file render.py loads.

  python scripts/make_scene.py --project my-film

The generated file is tiny: it puts this skill's scripts on sys.path and calls
storyboard.build_film(doc, project=doc.dir). Re-run it if the skill moves; the
storyboard itself reads beats.json + plan.json at render time, so re-planning
never needs a re-render of the scene file.
"""
import argparse
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import paths  # noqa: E402


TEMPLATE = '''"""Generated by automatic-storyteller-animate. Renders from beats.json + plan.json."""
import pathlib
import sys

SCRIPTS = pathlib.Path({scripts!r})
if str(SCRIPTS) not in sys.path:
    sys.path.insert(0, str(SCRIPTS))

from storyboard import build_film as _build_film


def build_film(doc):
    return _build_film(doc, project=doc.dir)
'''


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--project", required=True)
    a = ap.parse_args()
    proj = paths.project_dirs(a.project)
    out = proj / "scene.py"
    out.write_text(TEMPLATE.format(scripts=str(paths.SCRIPTS)), encoding="utf-8")
    print(f"scene: {out}")


if __name__ == "__main__":
    main()
